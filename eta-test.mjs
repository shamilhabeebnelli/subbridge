import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}), headless: true, args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
const errors = []; page.on('pageerror', (e) => errors.push(e.message));
await page.route('https://api.mymemory.translated.net/**', async (route) => {
  await new Promise((r) => setTimeout(r, 600));
  route.fulfill({ json: { responseStatus: 200, responseData: { translatedText: 'x' } } });
});
let srt = ''; for (let i = 0; i < 60; i++) srt += `${i + 1}\n00:00:${String(i % 60).padStart(2, '0')},000 --> 00:00:${String(i % 60).padStart(2, '0')},900\nLine number ${i} here\n\n`;
await page.goto('file://' + process.cwd() + '/index.html');
await page.locator('input[type=file]').setInputFiles({ name: 'f.srt', mimeType: 'text/plain', buffer: Buffer.from(srt) });
await page.getByLabel('To language').selectOption('malayalam');
await page.getByRole('checkbox').check();
await page.getByRole('button', { name: 'Translate', exact: true }).click();
await page.waitForSelector('.eta');
const first = await page.locator('.eta').innerText(); console.log('first:', first);
assert.match(first, /Estimating/);
await page.waitForFunction(() => /Estimated time left/.test(document.querySelector('.eta')?.textContent || ''), null, { timeout: 30000 });
const t = await page.locator('.eta').innerText(); console.log('later:', t);
await page.screenshot({ path: '/downloads/subbridge-eta-mobile.png' });
const w = await page.evaluate(() => document.documentElement.scrollWidth); assert.ok(w <= 391, 'no horizontal overflow, width ' + w);
await page.getByRole('button', { name: 'Stop' }).click();
await page.waitForFunction(() => !document.querySelector('.eta'));
console.log('eta hidden after Stop');
await page.getByRole('button', { name: 'Continue translating' }).click();
await page.waitForSelector('.eta');
assert.match(await page.locator('.eta').innerText(), /Estimating/); console.log('resume restarts as Estimating');
await page.getByRole('button', { name: 'Stop' }).click();
assert.equal(errors.length, 0, errors.join());
console.log('ETA browser checks passed'); await browser.close();
